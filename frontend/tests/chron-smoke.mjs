import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {DEFAULT_STATE} from '../src/core.js';

const browser=await chromium.launch({headless:true});
const smokeState={...DEFAULT_STATE,widgets:[{id:'chron-clock',type:'clock',title:'Chron clock',x:150,y:180,width:260,height:160,zone:'UTC'}]};
const labelPosition=page=>page.locator('.glyph-station').first().boundingBox();
try{
 for(const [width,height] of [[390,844],[1440,900]]){
  const page=await browser.newPage({viewport:{width,height},hasTouch:width<600});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(state=>localStorage.setItem('geo-draft',JSON.stringify(state)),smokeState);
  await page.goto(process.env.GEO_UI_URL||'http://127.0.0.1:4174');
  await page.locator('.country-label').first().waitFor({state:'attached'});
  await page.getByRole('button',{name:'Layers',exact:true}).click();
  await page.getByPlaceholder('Find a layer').fill('International Date Line');
  const dateline=page.getByRole('switch',{name:'International Date Line'});
  await dateline.click();
  await page.locator('.date-line-label').first().waitFor({state:'attached'});
  await page.locator('.layer-info summary').click();
  await page.getByText(/political International Date Line bends around/).waitFor();
  await dateline.click();
  await page.locator('.date-line-label').waitFor({state:'detached'});
  await page.keyboard.press('Escape');
  const beforeTransform=await page.locator('.country-label').first().evaluate(el=>el.style.transform);
  await page.getByRole('button',{name:'Enter Chron mode'}).click();
  await page.getByRole('navigation',{name:'Local solar time scale'}).waitFor();
  assert.equal(await page.locator('.chron-hour-label.solar-noon').evaluate(el=>el.style.left),'50%');
  assert.equal(await page.locator('.chron-hour-label.solar-noon small').textContent(),'SOLAR NOON');
  assert.equal(await page.locator('.chron-mode .map-tools').isVisible(),false);
  assert.equal(await page.locator('.hero-clock').isVisible(),false,'avoid duplicating the Chron UTC clock');
  assert.equal(await page.locator('.chron-live').isVisible(),true,'the UTC clock remains visible');
  assert.equal(await page.locator('.world-clocks').isVisible(),true,'world clocks remain visible');
  const solarTimeScale=page.getByRole('navigation',{name:'Local solar time scale'});
  const mapBeforeClockSync=await labelPosition(page);
  const tokyoSync=page.getByRole('button',{name:'Sync Chron to Tokyo',exact:true});
  await tokyoSync.click();
  assert.equal(await tokyoSync.getAttribute('aria-pressed'),'true','clicking a world clock selects its location as the Chron reference');
  const civilTimeScale=page.getByRole('navigation',{name:'Clock time scale synced to Tokyo'});
  await civilTimeScale.waitFor();
  assert.equal(await civilTimeScale.locator('.clock-noon small').textContent(),'LOCAL NOON');
  assert.notEqual(await solarTimeScale.evaluate(el=>getComputedStyle(el).backgroundImage),await civilTimeScale.evaluate(el=>getComputedStyle(el).backgroundImage),'the solar and civil rulers use distinct visual bands');
  assert.equal(await page.locator('.chron-overlay line').evaluate(el=>Number(el.getAttribute('x1'))),width/2,'the solar-noon meridian stays centered while civil time is shown separately');
  const mapAfterClockSync=await labelPosition(page);
  assert(Math.abs(mapAfterClockSync.x-mapBeforeClockSync.x)<1,'selecting a world clock does not rotate the solar-accurate map');
  await tokyoSync.click();
  await solarTimeScale.waitFor();
  assert.equal(await page.locator('.chron-clock-time-scale').count(),0,'toggling the selected clock off restores the single solar scale');
  assert.equal(await page.locator('.widget-stage .widget').isVisible(),true,'custom widgets remain visible');
  const showControls=page.getByRole('button',{name:'Show layers and settings'});
  await showControls.click();
  await page.getByRole('navigation',{name:'Display controls'}).waitFor();
  await page.getByRole('button',{name:'Layers',exact:true}).click();
  await page.getByRole('complementary',{name:'layers panel'}).waitFor();
  await page.getByPlaceholder('Find a layer').fill('');
  assert.equal(await page.getByRole('switch',{name:'Air quality · PM2.5'}).isDisabled(),false,'layer controls stay usable in Chron');
  await page.getByRole('button',{name:'Hide layers and settings'}).click();
  assert.equal(await page.getByRole('navigation',{name:'Display controls'}).isVisible(),false);
  assert.equal(await page.locator('.drawer').isVisible(),false);
  await page.getByRole('button',{name:'Show layers and settings'}).click();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('complementary',{name:'settings panel'}).waitFor();
  assert.equal(await page.getByLabel('London map latitude').inputValue(),'51.5074','named clocks retain a real map location for civil-time alignment');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('complementary',{name:'settings panel'}).isVisible(),false,'Escape closes the settings panel first');
  assert.equal(await page.getByRole('navigation',{name:'Display controls'}).isVisible(),true,'the rail stays open after closing its panel');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('navigation',{name:'Display controls'}).isVisible(),false,'Escape collapses the rail');
  await page.getByRole('button',{name:'Show layers and settings'}).click();
  await page.getByRole('button',{name:'Sync Chron to London',exact:true}).click();
  await page.getByRole('navigation',{name:'Clock time scale synced to London'}).waitFor();
  await page.getByRole('button',{name:'Hide all'}).click();
  assert.equal(await page.locator('.world-clocks').isVisible(),false,'Hide all returns to the uncluttered Chron view');
  assert.equal(await page.locator('.chron-clock-time-scale').count(),0,'hiding world clocks resets the optional civil scale');
  assert.equal(await page.locator('.widget-stage .widget').isVisible(),false);
  assert.equal(await page.locator('.chron-live').isVisible(),true,'the Chron UTC clock remains as the control entry point');
  await page.getByRole('button',{name:'Show layers and settings'}).click();
  await page.getByRole('button',{name:'Show all'}).click();
  assert.equal(await page.locator('.world-clocks').isVisible(),true,'Show all restores world clocks');
  assert.equal(await page.locator('.widget-stage .widget').isVisible(),true,'Show all restores custom widgets');
  assert((await page.locator('.chron-overlay .chron-grayline').getAttribute('d'))?.length>0);
  assert((await page.locator('.chron-overlay .chron-night').getAttribute('d'))?.length>0);
  assert.equal(await page.getByRole('button',{name:'Exit Chron',exact:true}).count(),1);
  const beforePan=await labelPosition(page);
  const overlayBeforePan=await page.locator('.chron-overlay').boundingBox();
  await page.mouse.move(width/2,height/2);await page.mouse.down();await page.mouse.move(width/2,height/2+70,{steps:4});await page.mouse.up();
  const afterVerticalPan=await labelPosition(page);
  const overlayAfterPan=await page.locator('.chron-overlay').boundingBox();
  assert(afterVerticalPan.y>beforePan.y+30,'dragging vertically moves the map north/south');
  assert(Math.abs((overlayAfterPan.y-overlayBeforePan.y)-(afterVerticalPan.y-beforePan.y))<2,'the day/night and grayline overlay follows the map when panning vertically');
  assert(Math.abs(afterVerticalPan.x-beforePan.x)<4,'vertical dragging does not shift solar longitude');
  await page.mouse.move(width/2,height/2);await page.mouse.down();await page.mouse.move(width/2+70,height/2,{steps:4});await page.mouse.up();
  const afterHorizontalDrag=await labelPosition(page);
  assert(Math.abs(afterHorizontalDrag.x-afterVerticalPan.x)<4,'horizontal dragging remains locked');
  assert(Math.abs(afterHorizontalDrag.y-afterVerticalPan.y)<4,'horizontal dragging does not change latitude');
  await page.screenshot({path:`/home/tyler/.hermes/cache/scratch/geochron-reference/chron-${width}.png`});
  const lockedClass=await page.locator('.leaflet-container').evaluate(el=>el.classList.contains('leaflet-grab'));
  assert.equal(lockedClass,false,'Chron disables map dragging');
  await page.waitForTimeout(1100);
  const duringTransform=await page.locator('.country-label').first().evaluate(el=>el.style.transform);
  assert.notEqual(duringTransform,beforeTransform,'Entering Chron rotates the map to noon-centered world view');
  const afterTimeTick=await labelPosition(page);
  assert(Math.abs(afterTimeTick.y-afterHorizontalDrag.y)<4,'north/south pan persists as Chron time advances');
  const lineX=await page.locator('.chron-overlay line').getAttribute('x1');
  const mask=await page.locator('.chron-overlay .chron-night').getAttribute('d');
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('.chron-overlay line').getAttribute('x1'),lineX,'The noon meridian stays screen-centered');
  assert.equal(await page.locator('.chron-overlay .chron-night').getAttribute('d'),mask,'The day/night pattern remains fixed while the map turns');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.chron-time-scale').count(),0,'Escape exits Chron');
  assert.equal(await page.locator('.leaflet-container').evaluate(el=>el.classList.contains('leaflet-grab')),true,'Map dragging is restored after Chron');
  assert.deepEqual(errors,[]);
  console.log(`PASS Chron ${width}x${height}: fixed solar frame, vertical-only pan, clocks/widgets, collapsible controls, exit`);
  await page.close();
 }
}finally{await browser.close()}
